#!/usr/bin/env python3
"""Builds Data/testsets/en_misspellings.tsv from Wikipedia's "Lists of common misspellings" (A-Z pages).

Text of Wikipedia is CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/); the pages are lists of real,
human-made misspellings with their corrections. Keeps only unambiguous pairs: one correction, ASCII letters only,
>= 4 letters, not equal. Deterministic output (sorted). Standard library only.

    python3 -I Tools/TypoData/fetch_misspellings.py OUT_TSV
"""
import re
import sys
import urllib.request

URL = "https://en.wikipedia.org/w/index.php?title=Wikipedia:Lists_of_common_misspellings/{}&action=raw"
LINE = re.compile(r"^\*\s*(?:\{\{search link\|\"?([^|\"}]+)\"?\|[^}]*\}\}|([^\s(]+))\s*\((.*)\)\s*$")
WORD = re.compile(r"^[a-z]{4,}$")


def clean_correction(text):
    text = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", text)  # wiki links
    if "," in text or ";" in text or "[" in text or "{" in text or "'" in text or "(" in text:
        return None
    return text.strip()


def main(out):
    pairs = set()
    for letter in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        req = urllib.request.Request(URL.format(letter), headers={"User-Agent": "iBoard-eval-data/1.0 (open-source keyboard; contact via github.com/shubhamsinghshubham777/iBoard)"})
        raw = urllib.request.urlopen(req, timeout=60).read().decode("utf-8")
        for line in raw.splitlines():
            m = LINE.match(line.strip())
            if not m:
                continue
            typo = (m.group(1) or m.group(2)).strip()
            fix = clean_correction(m.group(3))
            if not fix or not WORD.match(typo) or not WORD.match(fix) or typo == fix:
                continue
            pairs.add((typo, fix))
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Real human misspellings -> correction. Source: Wikipedia 'Lists of common misspellings' (CC BY-SA 4.0),\n")
        f.write("# generated by Tools/TypoData/fetch_misspellings.py. misspelling<TAB>correction\n")
        for typo, fix in sorted(pairs):
            f.write(f"{typo}\t{fix}\n")
    print(len(pairs), "pairs")


if __name__ == "__main__":
    main(sys.argv[1])
